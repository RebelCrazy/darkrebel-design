/* ── Core ── */
let currentLang = localStorage.getItem('ks_lang') || 'es';

function t(key) {
  return (TRANSLATIONS[currentLang] && TRANSLATIONS[currentLang][key])
      || (TRANSLATIONS['en'][key])
      || key;
}

function applyLang(lang) {
  currentLang = lang;
  localStorage.setItem('ks_lang', lang);
  document.documentElement.lang = lang;

  const dict = TRANSLATIONS[lang] || TRANSLATIONS['en'];

  /* text content */
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const v = dict[el.dataset.i18n];
    if (v !== undefined) el.textContent = v;
  });

  /* innerHTML (rich text: <br>, <span>, <a>) */
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const v = dict[el.dataset.i18nHtml];
    if (v !== undefined) el.innerHTML = v;
  });

  /* placeholders */
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const v = dict[el.dataset.i18nPlaceholder];
    if (v !== undefined) el.placeholder = v;
  });

  /* page title */
  const page = document.body && document.body.dataset.page;
  if (page) {
    const titleKey = 'page.' + page + '.title';
    const title = dict[titleKey];
    if (title) document.title = title;
  }

  /* lang toggle button label */
  const btn = document.getElementById('lang-toggle');
  if (btn) btn.textContent = lang === 'es' ? 'EN' : 'ES';

  /* notify other scripts */
  document.dispatchEvent(new CustomEvent('langchange', { detail: { lang } }));
}

function toggleLang() {
  applyLang(currentLang === 'es' ? 'en' : 'es');
}

window.t             = t;
window.applyLang     = applyLang;
window.toggleLang    = toggleLang;
window.getCurrentLang = () => currentLang;

/* Apply on load */
(function init() {
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => applyLang(currentLang));
  } else {
    applyLang(currentLang);
  }
})();
